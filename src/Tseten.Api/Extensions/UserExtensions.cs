using Tseten.Core;

namespace Tseten.Api;

public static class UserExtensions
{
    public static UserDto ToDto(this User user)
    {
        return new UserDto
        {
            UserId = user.UserId,
            Username = user.Username,
            DefaultProfileId = user.DefaultProfileId,
            Roles = user.Roles.Select(r => r.ToDto()).ToList()
        };
    }
}
